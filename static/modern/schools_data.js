/**
 * Helper untuk menginisialisasi 2-step dropdown sekolah (Jenis Sekolah -> Nama Sekolah)
 * @param {HTMLElement|string} categorySelectEl - Dropdown Jenis Sekolah
 * @param {HTMLElement|string} schoolSelectEl - Dropdown Nama Sekolah
 * @param {HTMLElement|string} [addressInputEl] - Textarea/Input Alamat Sekolah (opsional)
 * @param {string} [initialValue] - Nilai awal nama sekolah (opsional)
 */
window.initSchoolSelector = function(categorySelectEl, schoolSelectEl, addressInputEl, initialValue) {
  const catEl = typeof categorySelectEl === 'string' ? document.getElementById(categorySelectEl) : categorySelectEl;
  const schEl = typeof schoolSelectEl === 'string' ? document.getElementById(schoolSelectEl) : schoolSelectEl;
  const addrEl = addressInputEl ? (typeof addressInputEl === 'string' ? document.getElementById(addressInputEl) : addressInputEl) : null;

  if (!catEl || !schEl) return;

  const categories = [
    "SMA NEGERI",
    "SMA SWASTA",
    "SMK NEGERI",
    "SMK SWASTA",
    "SMP NEGERI",
    "SMP SWASTA"
  ];

  // Inject search box if missing
  let searchInput = (schEl.previousElementSibling && schEl.previousElementSibling.classList.contains('school-search-input')) 
    ? schEl.previousElementSibling 
    : null;

  if (!searchInput) {
    searchInput = document.createElement('input');
    searchInput.type = 'text';
    searchInput.className = 'form-control form-control-sm mb-1 school-search-input';
    searchInput.placeholder = '🔍 Ketik nama / alamat sekolah untuk mencari...';
    searchInput.style.fontSize = '0.85rem';
    searchInput.style.display = 'none';
    schEl.parentNode.insertBefore(searchInput, schEl);
  }

  // Isi opsi Jenis Sekolah jika belum terisi
  if (catEl.options.length <= 1) {
    catEl.innerHTML = '<option value="">-- Pilih Jenis Sekolah --</option>';
    categories.forEach(cat => {
      const opt = document.createElement('option');
      opt.value = cat;
      opt.textContent = cat;
      catEl.appendChild(opt);
    });
  }

  function updateSchools(selectedCategory, selectSchoolName) {
    schEl.innerHTML = '<option value="">-- Pilih Nama Sekolah --</option>';
    if (!selectedCategory || !window.SCHOOLS_DATA || !window.SCHOOLS_DATA[selectedCategory]) {
      schEl.disabled = true;
      if (searchInput) searchInput.style.display = 'none';
      return;
    }
    schEl.disabled = false;
    if (searchInput) searchInput.style.display = 'block';

    const schools = window.SCHOOLS_DATA[selectedCategory];
    const query = (searchInput ? searchInput.value : '').toLowerCase().trim();

    let count = 0;
    schools.forEach(s => {
      const fullText = (s.name + ' ' + (s.address || '')).toLowerCase();
      if (query && !fullText.includes(query)) return;

      const opt = document.createElement('option');
      opt.value = s.name;
      opt.textContent = s.address ? `${s.name} - ${s.address}` : s.name;
      opt.dataset.address = s.address || '';
      if (selectSchoolName && (s.name === selectSchoolName || selectSchoolName.includes(s.name))) {
        opt.selected = true;
      }
      schEl.appendChild(opt);
      count++;
    });

    if (count === 0 && query) {
      const emptyOpt = document.createElement('option');
      emptyOpt.value = '';
      emptyOpt.textContent = `Tidak ditemukan sekolah dengan kata kunci "${query}"`;
      emptyOpt.disabled = true;
      schEl.appendChild(emptyOpt);
    }
  }

  if (searchInput) {
    searchInput.addEventListener('input', function() {
      updateSchools(catEl.value);
    });
  }

  catEl.addEventListener('change', function() {
    if (searchInput) searchInput.value = '';
    updateSchools(catEl.value);
  });

  schEl.addEventListener('change', function() {
    if (addrEl && schEl.selectedIndex > 0) {
      const opt = schEl.options[schEl.selectedIndex];
      if (opt.dataset.address && (!addrEl.value || addrEl.value.trim() === '')) {
        addrEl.value = opt.dataset.address;
      }
    }
  });

  // Pre-select jika ada nilai awal
  if (initialValue && window.SCHOOLS_DATA) {
    let foundCat = '';
    for (const cat in window.SCHOOLS_DATA) {
      if (window.SCHOOLS_DATA[cat].some(s => s.name === initialValue)) {
        foundCat = cat;
        break;
      }
    }
    if (foundCat) {
      catEl.value = foundCat;
      updateSchools(foundCat, initialValue);
    } else {
      updateSchools(catEl.value);
    }
  } else {
    updateSchools(catEl.value);
  }
};

